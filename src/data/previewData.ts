export const createEmptyEightSeats = (
  presets: Partial<Record<number, Partial<GuestSeat>>> = {}
): GuestSeat[] =>
  Array.from({ length: 8 }, (_, idx) => {
    const seatNumber = idx + 1;
    const preset = presets[seatNumber] ?? {};
    return {
      seatNumber,
      status: preset.status ?? 'AVAILABLE',
      occupantUid: preset.occupantUid,
      occupantName: preset.occupantName,
      occupantUsername: preset.occupantUsername,
      occupantAvatarColor: preset.occupantAvatarColor,
      isMuted: preset.isMuted ?? false,
      isSpeaking: preset.isSpeaking ?? false,
    };
  });

